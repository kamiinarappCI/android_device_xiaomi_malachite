#!/bin/bash
# crDroid 17.0 (Android 17) tree and build on the C: SSD. crDroid is the main ROM line
# since 2026-11-10 (the LineageOS trees were removed that day).
#
#   bash /mnt/e/LineageOS-23.2-Malachite/tools/build_crdroid.sh
#
# First run: `repo init` of crdroidandroid/android 17.0, the device fork's crdroid-17.0
# manifests/crdroid.xml as local manifest, `repo sync`, inline keys. REFERENCE=<tree>
# borrows objects from another checkout during that first sync and dissociates
# afterwards, so the tree never depends on it. Later runs: SYNC=1 to sync again
# (SYNC_JOBS, default 8); otherwise build only. SYNC_ONLY=1 stops after the sync.
# BRANCHES="..." merges fork branches on top (prepare_tree.sh, local merges only).
# Then build_malachite.sh with TOP at this tree, MALACHITE_ROM=crdroid and
# MALACHITE_VER=17.0: zip crDroid-17.0-<day>-UNOFFICIAL-malachite-test.zip.
#
# Do not edit this file while a build runs: bash reads it as it goes.
set -o pipefail
TOOLS=/mnt/e/LineageOS-23.2-Malachite/tools
SRC=/mnt/wsl/malachite-build
T=$SRC/crdroid-17.0
MANIFEST_URL=https://raw.githubusercontent.com/malachite-project/android_device_xiaomi_malachite/crdroid-17.0/manifests/crdroid.xml
LOG=$HOME/android/build-$(date +%Y%m%d-%H%M).log
phase() { echo "phase: $1 at $(date '+%F %T')" | tee -a "$LOG"; }
fail() { echo "build exit: 1 ($1)" | tee -a "$LOG"; exit 1; }

bash "$TOOLS/build_disk.sh" up || fail "build disk"
# build_disk.sh's keeper watches /build/.last-use; keep it alive for the whole run.
( while sleep 60; do touch "$SRC/.last-use" 2>/dev/null; done ) &
HEARTBEAT=$!
trap 'kill $HEARTBEAT 2>/dev/null' EXIT

mkdir -p "$T" && cd "$T" || fail "no $T"
phase "crdroid-17.0 tree at $T"
if [ ! -d .repo ]; then
  # repo's --dissociate cannot work here: repo marks shared object stores
  # preciousObjects, so its `repack -a -d` is refused. dissociate_tree.sh does it after the sync.
  phase "repo init${REFERENCE:+ (reference $REFERENCE)}"
  repo init -q -u https://github.com/crdroidandroid/android.git -b 17.0 --git-lfs \
    --no-clone-bundle ${REFERENCE:+--reference="$REFERENCE"} 2>&1 | tee -a "$LOG"
  [ "${PIPESTATUS[0]}" = 0 ] || fail "repo init failed"
  SYNC=1
fi
mkdir -p .repo/local_manifests
curl -fsSL "$MANIFEST_URL" -o .repo/local_manifests/crdroid.xml.new &&
  mv .repo/local_manifests/crdroid.xml.new .repo/local_manifests/crdroid.xml ||
  fail "no crdroid-17.0 local manifest"

if [ "${SYNC:-0}" = 1 ]; then
  phase "repo sync"
  [ -d build/soong ] && git -C build/soong checkout -- ui/build/soong.go 2>/dev/null  # memory patch, reapplied by build_malachite.sh
  # android.googlesource.com answers HTTP 429 when pushed hard; SYNC_JOBS=4 eases
  # off, --retry-fetches retries the refused fetches.
  repo sync -c -j"${SYNC_JOBS:-8}" --retry-fetches=5 --no-tags --no-clone-bundle --force-sync -q \
    2>&1 | tail -30 | tee -a "$LOG"
  [ "${PIPESTATUS[0]}" = 0 ] || fail "repo sync failed"
  # Nothing may still borrow objects from another tree (it would break once that is gone).
  if [ -n "$(find .repo -path '*/objects/info/alternates' -print -quit 2>/dev/null)" ]; then
    phase "dissociate_tree.sh"
    bash "$TOOLS/dissociate_tree.sh" "$T" 2>&1 | tail -15 | tee -a "$LOG"
    [ "${PIPESTATUS[0]}" = 0 ] || fail "dissociate_tree.sh failed"
  fi
  alt=$(find .repo -path '*/objects/info/alternates' 2>/dev/null | wc -l)
  echo "object alternates left: $alt" | tee -a "$LOG"
  [ "$alt" = 0 ] || fail "$alt projects still borrow objects"
fi
[ "${SYNC_ONLY:-0}" = 1 ] && { echo "sync done at $(date '+%F %T')" | tee -a "$LOG"; exit 0; }

if [ ! -f vendor/lineage-priv/keys/keys.mk ]; then
  phase "inline keys"
  TOP=$T bash "$TOOLS/setup_inline_keys.sh" 2>&1 | tail -5 | tee -a "$LOG"
  [ "${PIPESTATUS[0]}" = 0 ] || fail "setup_inline_keys.sh failed"
fi

phase "prepare_tree.sh ${BRANCHES:-}"
# shellcheck disable=SC2086
TOP=$T BASE=crdroid-17.0 MANIFEST=$T/.repo/local_manifests/crdroid.xml \
  bash "$TOOLS/prepare_tree.sh" ${BRANCHES:-} 2>&1 | tee -a "$LOG"
[ "${PIPESTATUS[0]}" = 0 ] || fail "prepare_tree.sh failed"

# crDroid's vendor config must load vendor/lineage-priv/keys/keys.mk like LineageOS's.
phase "build_malachite.sh"
TOP=$T MALACHITE_ROM=crdroid MALACHITE_VER=17.0 PREPARE=0 SYNC=0 \
  bash "$TOOLS/build_malachite.sh"
