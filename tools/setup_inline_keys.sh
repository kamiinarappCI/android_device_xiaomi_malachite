#!/usr/bin/env bash
# Inline signing: the build signs every APK and APEX with our keys while it
# compiles, so sign_target_files_apks (about 19 of the 33 minutes after
# compiling on 2026-10-16) is no longer needed. Run once, and again after
# new keys or a LineageOS update that adds APEXes:
#
#   bash /mnt/e/LineageOS-23.2-Malachite/tools/setup_inline_keys.sh [reference-signed-target_files.zip]
#
# Copies ~/.android-certs into vendor/lineage-priv/keys of the build tree (not
# a git project; it is never pushed) and writes keys.mk and Android.bp there.
# vendor/lineage/config/common.mk includes vendor/lineage-priv/keys/keys.mk;
# with PRODUCT_DEFAULT_DEV_CERTIFICATE under vendor/lineage-priv/ the build is
# tagged release-keys.
#
# Every key is mapped the way sign_build.sh maps it, so an inline-signed build
# has the signatures of a re-signed one and dirty-flashes over it:
#   testkey, devkey               -> releasekey (sign_target_files_apks -d)
#   platform, shared, media, ...  -> the key of the same name
#   nfc                           -> nfc
#   APEX <name> container         -> <name> (PRODUCT_CERTIFICATE_OVERRIDES)
#   APEX payload key file <base>  -> <name>.pem of the APEX using it
#   APKs inside APEXes (APEX_APKS below, the list sign_build.sh uses)
#                                 -> releasekey
# The APEX list comes from the reference build's META/apexkeys.txt.
# check_inline_signing.py compares each new build with that reference before
# it is packaged, so a key that maps differently stops the build.
#
# To go back to re-signing after the build: delete vendor/lineage-priv (build
# once more so every APK is re-signed with the test keys first).
set -euo pipefail
TOP=${TOP:-$HOME/android/lineage}
CERTS=${CERTS:-$HOME/.android-certs}
REF=${1:-$(ls -t "$HOME"/android/releases/*/signed-target_files.zip 2>/dev/null | head -1)}
K=$TOP/vendor/lineage-priv/keys
AVBTOOL=$TOP/external/avb/avbtool.py

# Same list as sign_build.sh: APKs shipped inside APEXes that the LineageOS
# wiki signs with releasekey.
APEX_APKS="com.android.appsearch.apk AdServicesApk FederatedCompute HalfSheetUX
HealthConnectBackupRestore HealthConnectController OsuLogin SafetyCenterResources
ServiceConnectivityResources ServiceUwbResources ServiceWifiResources
TelecomServiceResources TelecomUi WebAppService WifiDialog"

[[ -f $REF ]] || { echo "no reference signed-target_files.zip: '$REF'"; exit 1; }
[[ -f $CERTS/releasekey.pk8 ]] || { echo "no keys in $CERTS"; exit 1; }
echo "reference: $REF"

rm -rf "$K.new"
mkdir -p "$K.new"
chmod 700 "$TOP/vendor/lineage-priv" "$K.new"
cp -p "$CERTS"/*.pk8 "$CERTS"/*.pem "$K.new"/
# sign_target_files_apks -d maps testkey and devkey to releasekey.
for k in testkey devkey; do
  cp -p "$CERTS/releasekey.pk8" "$K.new/$k.pk8"
  cp -p "$CERTS/releasekey.x509.pem" "$K.new/$k.x509.pem"
done

declare -A payload_owner=()
overrides=()
bp="// Generated by setup_inline_keys.sh. Do not edit.
"
missing=0
while IFS= read -r line; do
  [[ $line == *'container_certificate="PRESIGNED"'* ]] && continue
  name=$(sed -n 's/^name="\([^"]*\)\.apex".*/\1/p' <<<"$line")
  [[ -n $name ]] || continue
  priv=$(sed -n 's/.* private_key="\([^"]*\)".*/\1/p' <<<"$line")
  pub=$(sed -n 's/.* public_key="\([^"]*\)".*/\1/p' <<<"$line")
  if [[ ! -f $CERTS/$name.pk8 || ! -f $CERTS/$name.x509.pem || ! -f $CERTS/$name.pem ]]; then
    echo "missing key: $CERTS/$name (run make_keys.sh)"; missing=1; continue
  fi
  # Container: always through an override module, which wins over both a
  # plain certificate name and a ":module" certificate.
  overrides+=("$name:$name.malachite.certificate")
  bp+="
android_app_certificate {
    name: \"$name.malachite.certificate\",
    certificate: \"$name\",
}
"
  # Payload: soong looks for the apex_key's own file names in this directory
  # and silently falls back to the test key next to the module when they are
  # missing, so provide them under those names.
  base=$(basename "$priv" .pem)
  pubbase=$(basename "$pub" .avbpubkey)
  if [[ -n ${payload_owner[$base]:-} && ${payload_owner[$base]} != "$name" ]]; then
    echo "note: $name and ${payload_owner[$base]} share the payload key file $base.pem;" \
         "both get ${payload_owner[$base]}'s key"
    continue
  fi
  payload_owner[$base]=$name
  cp -p "$CERTS/$name.pem" "$K.new/$base.pem"
  python3 "$AVBTOOL" extract_public_key --key "$K.new/$base.pem" --output "$K.new/$pubbase.avbpubkey"
done < <(unzip -p "$REF" META/apexkeys.txt)
[[ $missing == 0 ]] || { rm -rf "$K.new"; exit 1; }

# The cp above also puts the payload key of every APEX the reference build doesn't
# have (new in a later Android, e.g. 17's com.android.webapp) here under its own
# name. Soong then signs with it but checks it against the module's own
# .avbpubkey and stops ("pubkey doesn't match"), so give each one its public key.
for pem in "$K.new"/*.pem; do
  [[ $pem == *.x509.pem ]] && continue
  pub=${pem%.pem}.avbpubkey
  [[ -f $pub ]] || python3 "$AVBTOOL" extract_public_key --key "$pem" --output "$pub"
done

bp+="
android_app_certificate {
    name: \"malachite.releasekey.certificate\",
    certificate: \"releasekey\",
}
"
for apk in $APEX_APKS; do
  overrides+=("$apk:malachite.releasekey.certificate")
done

{
  echo "# Generated by setup_inline_keys.sh. Do not edit."
  echo "PRODUCT_DEFAULT_DEV_CERTIFICATE := vendor/lineage-priv/keys/releasekey"
  echo "PRODUCT_OTA_PUBLIC_KEYS := vendor/lineage-priv/keys/releasekey"
  echo "PRODUCT_MAINLINE_BLUETOOTH_SEPOLICY_DEV_CERTIFICATES := vendor/lineage-priv/keys"
  echo "PRODUCT_CERTIFICATE_OVERRIDES := \\"
  for o in "${overrides[@]}"; do echo "    $o \\"; done
  echo
} > "$K.new/keys.mk"
printf '%s' "$bp" > "$K.new/Android.bp"
cat > "$K.new/BUILD.bazel" <<'EOF'
filegroup(
    name = "android_certificate_directory",
    srcs = glob([
        "*.pk8",
        "*.pem",
    ]),
    visibility = ["//visibility:public"],
)
EOF
chmod 600 "$K.new"/*
rm -rf "$K"
mv "$K.new" "$K"
echo "inline keys ready in $K: ${#overrides[@]} certificate overrides," \
     "$(ls "$K"/*.avbpubkey | wc -l) APEX payload keys"
