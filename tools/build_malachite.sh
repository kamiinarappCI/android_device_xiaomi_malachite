#!/bin/bash
# Build malachite in WSL and make the signed, flashable OTA. Same settings
# every time, so later builds reuse ccache and out/ and only rebuild what
# changed.
#
#   bash /mnt/e/LineageOS-23.2-Malachite/tools/build_malachite.sh
#   BRANCHES="fix/lcd-density feature/gpu-interaction-floor" bash .../build_malachite.sh
#
# Environment:
#   BRANCHES="a b"           feature branches to test on top of lineage-23.2
#                            (prepare_tree.sh). Empty: plain lineage-23.2,
#                            the only state a release is built from
#   PREPARE=0                build the tree as it is (no prepare_tree.sh)
#   SYNC=1                   `repo sync` first: LineageOS's latest for every
#                            project we don't fork (our forks are set by
#                            prepare_tree.sh afterwards)
#   JOBS=6                   parallel jobs (24 GB RAM: 6 avoids swapping on
#                            the big link and dex steps)
#   (default)                release type: ro.debuggable=0, ADB authorisation on.
#                            Every build, test builds included, is this type.
#   DIAGNOSTIC=1             only for chasing a bootloop: debuggable, no ADB
#                            authorisation (WITH_ADB_INSECURE)
#   SIGN=1                   make the OTA after a successful build
#
# Signing: with vendor/lineage-priv/keys/keys.mk (setup_inline_keys.sh) the
# build signs as it compiles; check_inline_signing.py then compares every
# signature with the newest release before package_build.sh makes the OTA.
# Without it, sign_build.sh re-signs the target files first (~19 min more).
#
# All types use the same keys. Do not edit this file while a build runs: bash
# reads it as it goes.
#
# Never run `m clean` or delete out/ between builds unless a build is broken
# by stale output: a clean build takes most of a day, an incremental one
# usually under an hour.
set -o pipefail
TOP=${TOP:-$HOME/android/lineage}
TOOLS=/mnt/e/LineageOS-23.2-Malachite/tools
# The source checkout and out/ are on the C: SSD (build_disk.sh); attach them.
if [ -d "$HOME/android/lineage-repo" ]; then  # moved to the SSD (migrate_build_disk.sh)
  bash "$TOOLS/build_disk.sh" up || exit 1
  # Keep the build disk attached while this build runs (its keeper stops 3 h
  # after the last heartbeat).
  ( while sleep 60; do touch "$TOP/.build-heartbeat" 2>/dev/null; done ) &
  HEARTBEAT=$!
  trap 'kill $HEARTBEAT 2>/dev/null' EXIT
  touch "$TOP/.build-heartbeat"
fi
cd "$TOP" || exit 1

# ccache: one fixed cache for this tree, on the SSD next to it when it is there
# (overrides ~/.bashrc's CCACHE_DIR for this build only).
export USE_CCACHE=1
export CCACHE_EXEC=$(command -v ccache)
if [ -d /mnt/wsl/malachite-build/ccache ]; then
  export CCACHE_DIR=/mnt/wsl/malachite-build/ccache
else
  export CCACHE_DIR=$HOME/.cache/ccache
fi
[ -n "$CCACHE_EXEC" ] || { echo "ccache not installed"; exit 1; }
mkdir -p "$CCACHE_DIR"
ccache -M 100G >/dev/null   # a full build fills ~25-35 GB compressed
ccache -z >/dev/null   # per-build hit statistics

# Release type unless DIAGNOSTIC=1. LineageOS tests `ifdef WITH_ADB_INSECURE`,
# so it must be unset, not "false". The old debuggable "tester" type is gone
# (2026-10-26): it only made the ROM detectable.
# MALACHITE_DIAGNOSTICS=true also keeps every boot's logcat in /data/misc/logd
# (device.mk); releases leave it unset.
if [ "${DIAGNOSTIC:-0}" = 1 ]; then
  export WITH_ADB_INSECURE=true MALACHITE_DIAGNOSTICS=true; unset MALACHITE_RELEASE
else
  unset WITH_ADB_INSECURE MALACHITE_DIAGNOSTICS; export MALACHITE_RELEASE=true
fi
JOBS=${JOBS:-6}
LOG=$HOME/android/build-$(date +%Y%m%d-%H%M).log
KEYS=$TOP/vendor/lineage-priv/keys
phase() { echo "phase: $1 at $(date '+%F %T')" | tee -a "$LOG"; }

phase start
if [ "${SYNC:-0}" = 1 ]; then
  phase "repo sync"
  repo sync -c -j4 --no-tags --no-clone-bundle -q 2>&1 | tail -20 | tee -a "$LOG"
  [ "${PIPESTATUS[0]}" = 0 ] || { echo "build exit: 1 (repo sync failed)" | tee -a "$LOG"; exit 1; }
fi
if [ "${PREPARE:-1}" = 1 ]; then
  # shellcheck disable=SC2086
  bash "$TOOLS/prepare_tree.sh" ${BRANCHES:-} 2>&1 | tee -a "$LOG"
  [ "${PIPESTATUS[0]}" = 0 ] || { echo "build exit: 1 (prepare_tree.sh refused)" | tee -a "$LOG"; exit 1; }
fi

# Android 17's soong_build fills the VM's ~63 GiB of RAM and swap: Go lets the heap
# reach twice the live data, so whether a build fits depends on when the last
# collection ran (OOM-killed 2026-11-06 at 62.5 GiB). GOMEMLIMIT makes Go collect
# before the ceiling; the patch passes it through the rule's "env -i". Host memory
# only, the ROM does not change. build_lineage24.sh reverts it before a repo sync.
if [ "${MALACHITE_VER:-}" = 24.0 ] || [ "${MALACHITE_ROM:-}" = crdroid ]; then
  SOONG_PATCH=$TOOLS/../patches/soong-memory-limit-24.0.patch
  git -C build/soong apply --reverse --check "$SOONG_PATCH" 2>/dev/null ||
    git -C build/soong apply "$SOONG_PATCH" ||
    { echo "build exit: 1 (soong memory patch refused)" | tee -a "$LOG"; exit 1; }
  export MALACHITE_SOONG_MEMLIMIT=${MALACHITE_SOONG_MEMLIMIT:-54GiB}
fi

source build/envsetup.sh >/dev/null
breakfast malachite userdebug || exit 1
{
  echo "start: $(date)"
  echo "WITH_ADB_INSECURE=${WITH_ADB_INSECURE:-unset}" \
       "MALACHITE_RELEASE=${MALACHITE_RELEASE:-unset} JOBS=$JOBS CCACHE_DIR=$CCACHE_DIR"
  echo "config: $(get_build_var PRODUCT_SYSTEM_EXT_PROPERTIES | tr ' ' '\n' | grep ro.adb.secure)" \
       "not_debuggable_in_userdebug=$(get_build_var PRODUCT_NOT_DEBUGGABLE_IN_USERDEBUG)"
  echo "signing: $([ -f "$KEYS/keys.mk" ] && echo "inline ($KEYS)" || echo "re-sign after the build")"
  [ -f "$HOME/android/tree-state.txt" ] && sed 's/^/  /' "$HOME/android/tree-state.txt"
} | tee -a "$LOG"

phase compile
mka -j"$JOBS" --skip-soong-tests target-files-package otatools 2>&1 | tee -a "$LOG"
status=${PIPESTATUS[0]}
{
  echo "build exit: $status at $(date)"
  ccache -s | sed -n '1,8p'
} | tee -a "$LOG"
[ "$status" = 0 ] || exit "$status"
[ "${SIGN:-1}" = 1 ] || exit 0

if [ -f "$KEYS/keys.mk" ]; then
  TF=$(ls -t "$OUT"/obj/PACKAGING/target_files_intermediates/*-target_files*.zip | head -1)
  REF=$(ls -t "$HOME"/android/releases/*/signed-target_files.zip 2>/dev/null | head -1)
  # The signature check (~3.5 min) runs beside the OTA generation; the OTA is
  # archived only if the check passes.
  phase "signature check against $REF, beside the OTA"
  GATE=$HOME/android/gate-$(date +%Y%m%d-%H%M).log
  python3 "$TOOLS/check_inline_signing.py" "$REF" "$TF" > "$GATE" 2>&1 &
  gate_pid=$!
  phase package
  CHECK_PID=$gate_pid CHECK_LOG=$GATE bash "$TOOLS/package_build.sh" "$TF" "$KEYS/releasekey" 2>&1 | tee -a "$LOG"
  status=${PIPESTATUS[0]}
else
  phase "re-sign and package"
  bash "$TOOLS/sign_build.sh" 2>&1 | tee -a "$LOG"
  status=${PIPESTATUS[0]}
fi
phase done
exit "$status"
